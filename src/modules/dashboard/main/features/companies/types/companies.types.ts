import { z } from "zod";

export const companiesSchema = z.object({
    name: z.string().min(1, "Name is required"),
    description: z.string().optional(),
    role: z.string().optional(),
    email: z.string().email().optional(),
    phone: z.string().optional(),
});

export interface Companies {
    id: string;
    name: string;
    description?: string | null;
    role?: string | null;
    email?: string | null;
    phone?: string | null;
    isActive: boolean;
    createdAt: string;
    updatedAt: string;
}

export type CompaniesCreatePayload = z.infer<typeof companiesSchema>;
export type CompaniesUpdatePayload = Partial<CompaniesCreatePayload>;
