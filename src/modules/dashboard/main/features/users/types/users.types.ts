import { z } from "zod";

export const usersSchema = z.object({
    name: z.string().min(1, "Name is required"),
    description: z.string().optional(),
    role: z.string().optional(),
    email: z.string().email().optional(),
    phone: z.string().optional(),
});

export interface Users {
    id: string;
    name: string;
    description?: string | null;
    role?: string | null;
    email?: string | null;
    phone?: string | null;
    isActive: boolean;
    createdAt: string;
    updatedAt: string;
}

export type UsersCreatePayload = z.infer<typeof usersSchema>;
export type UsersUpdatePayload = Partial<UsersCreatePayload>;
